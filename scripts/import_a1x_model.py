#!/usr/bin/env python3
"""MJCF ramienia Galaxea A1X dla blizniaka - z URDF producenta.

    python scripts/import_a1x_model.py                      # przebuduj src/lerobot_mp/robot/a1x/robot/a1x.xml
    python scripts/import_a1x_model.py --out /tmp/a1x.xml   # to samo obok, do porownania

To jest generator `sim/urdf2mjcf.py` z galaxeo-manipulators (ta sama deterministyczna
droga ElementTree + minidom), z argumentami zamiast sciezek na sztywno i z szescioma
regulami, ktorych blizniak potrzebuje (wypisane tez w naglowku wygenerowanego pliku):

1. Staw `gripper_finger_joint1` nazywa sie `gripper` (staw, jego aktuator i odwolanie
   w rownosci) - ta sama nazwa chwytaka co w SO-101 i w `config.GRIPPER`. Druga
   szczeka zostaje `gripper_finger_joint2`, sprzezona rownoscia. Keyframe `home`
   bez zmian.
2. Aktuatory nazywaja sie jak ich stawy (`arm_joint1..6`, `gripper`) - scena szuka
   aktuatora po nazwie stawu (w galaxeo: `arm1..arm6`, `gripper_finger1`).
3. Zagiete czubki szczek (skrzynki kolizyjne na koncu kazdej szczeki) maja nazwy
   `finger1_tip` / `finger2_tip` - `RobotSpec.fingertips`.
4. `<option integrator="implicitfast" timestep="0.002" cone="elliptic" impratio="10"/>`:
   krok z `sim/scene.xml` galaxeo, stozek i impratio jak w SO-101 z Menagerie - scena
   blizniaka kopiuje opcje z modelu ramienia. `noslip_iterations` z galaxeo celowo
   pominiete (scena go nie kopiuje, MuJoCo Warp go nie wspiera).
5. Site `tcp` taki, jak generuje galaxeo (`x` - podejscie, `y` - zamykanie szczek),
   bez obrotu; osie podaje `RobotSpec.tcp_approach/tcp_closing`.
6. Rownosc sprzegajaca szczeki jest sztywniejsza niz domyslna: `solref="0.01 1"`,
   `solimp="0.99 0.999 0.001 0.5 2"`. W prawdziwym A1X to jeden sztywny stopien
   swobody (sterownik publikuje druga szczeke jako lustro skoku pierwszej), a
   domyslna rownosc (solref 0.02, solimp 0.9/0.95) trzyma druga szczeke tylko
   miekko: przy gwaltownych akcjach ramienia w RL (krok 5 ms) i kontaktach z
   blatem szczeki rozjezdzaly sie do ~36 mm. 0.01 s to najkrotsza stala czasu,
   jakiej MuJoCo uzywa przy kroku 5 ms (refsafe: 2 x krok) - krotsza nic tam nie
   zmienia; impedancja 0.99-0.999 robi reszte (najgorzej ok. 12 mm, zwykle 2-5 mm).

Siatki STL z `--meshes` sa kopiowane do katalogu `assets/` obok `--out` (`meshdir`).
Wynik zalezy tylko od URDF, wiec ponowne uruchomienie daje ten sam plik bajt w bajt
(pilnuje `tests/test_twin_a1x_sim.py`).
"""

from __future__ import annotations

import argparse
import os
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.dom import minidom

REPO = Path(__file__).resolve().parents[1]
ASSET_DIR = REPO / "src" / "lerobot_mp" / "robot" / "a1x" / "robot"
MESHDIR = "assets"

# Wzmocnienia serw pozycyjnych - "dosc sztywno, zeby trzymac poze pod grawitacja" (galaxeo).
KP = {"arm_joint1": 300, "arm_joint2": 600, "arm_joint3": 400,
      "arm_joint4": 150, "arm_joint5": 100, "arm_joint6": 60}
KP_GRIPPER = 1000
# Proste bryly kolizyjne zamiast siatek szczek (galaxeo): MuJoCo zderza siatki jako
# otoczki wypukle, a szczeka w ksztalcie L daje klin o skosnej scianie wewnetrznej,
# po ktorej chwytany obiekt sie wyslizguje. Uklad ciala szczeki: wozek za dlonia,
# plytka rownolegla do drugiej szczeki i zagiety do srodka czubek. Druga szczeka
# to lustro (y, z -> -y, -z).
FINGER1_BOXES = [   # (pozycja, polowy bokow, nazwa)
    ((-0.047, -0.0385, 0.017), (0.007, 0.027, 0.006), None),     # wozek za dlonia
    ((0.017, -0.0015, 0.0), (0.024, 0.0015, 0.010), None),       # plytka
    ((0.038, -0.0085, 0.0), (0.004, 0.0035, 0.006), "tip"),      # zagiety czubek (regula 3)
]
FINGER_COLLISION = {
    "gripper_finger_link1": [(p, hs, n and "finger1_tip") for p, hs, n in FINGER1_BOXES],
    "gripper_finger_link2": [((x, -y, -z), hs, n and "finger2_tip") for (x, y, z), hs, n in FINGER1_BOXES],
}
HOME = {"arm_joint2": 1.0, "arm_joint3": -1.6, "arm_joint4": 0.6, "gripper_finger_joint1": 0.03}
#: Regula 1: nazwy stawow w MJCF inne niz w URDF.
RENAME = {"gripper_finger_joint1": "gripper"}
#: Regula 4: opcje fizyki modelu.
OPTION = {"integrator": "implicitfast", "timestep": "0.002", "cone": "elliptic", "impratio": "10"}
#: Regula 6: sztywnosc rownosci sprzegajacej szczeki.
MIRROR_SOLREF = "0.01 1"
MIRROR_SOLIMP = "0.99 0.999 0.001 0.5 2"

HEADER = """<!-- Generated by scripts/import_a1x_model.py from {urdf} (Galaxea A1X vendor URDF,
     via galaxeo-manipulators sim/urdf2mjcf.py). Do not edit by hand.
     Post-processing rules:
     1. joint gripper_finger_joint1 -> gripper (joint, actuator, equality); keyframe home unchanged
     2. actuators named exactly like their joints
     3. curled finger-tip collision boxes named finger1_tip / finger2_tip
     4. option: implicitfast, timestep 0.002, cone elliptic, impratio 10 (no noslip_iterations)
     5. site tcp as generated: x = approach, y = jaw closing
     6. jaw mirror equality stiffened: solref 0.01 1, solimp 0.99 0.999 0.001 0.5 2 -->
"""


def fmt(v) -> str:
    return " ".join(f"{float(x):.6g}" for x in v)


def mesh_files(urdf: Path) -> list[str]:
    """Nazwy plikow siatek, do ktorych odwoluje sie URDF (bez sciezek `package://`)."""
    robot = ET.parse(urdf).getroot()
    return sorted({os.path.basename(m.get("filename")) for m in robot.iter("mesh")})


def generate(urdf: Path) -> str:
    """Tekst MJCF z URDF - bez zapisu na dysk."""
    robot = ET.parse(urdf).getroot()
    links = {link.get("name"): link for link in robot.findall("link")}
    joints = robot.findall("joint")
    children: dict[str, list[ET.Element]] = {}
    for j in joints:
        children.setdefault(j.find("parent").get("link"), []).append(j)
    root_link = next(n for n in links if n not in {j.find("child").get("link") for j in joints})

    mj = ET.Element("mujoco", model=robot.get("name"))
    ET.SubElement(mj, "compiler", angle="radian", eulerseq="XYZ", meshdir=MESHDIR, autolimits="true")
    ET.SubElement(mj, "option", OPTION)

    default = ET.SubElement(mj, "default")
    ET.SubElement(default, "joint", armature="0.01", damping="1")
    ET.SubElement(default, "position", forcelimited="true")
    d_vis = ET.SubElement(default, "default", {"class": "visual"})
    ET.SubElement(d_vis, "geom", type="mesh", contype="0", conaffinity="0", group="2")
    d_col = ET.SubElement(default, "default", {"class": "collision"})
    ET.SubElement(d_col, "geom", type="mesh", group="3")

    asset = ET.SubElement(mj, "asset")
    meshes: set[str] = set()
    world = ET.SubElement(mj, "worldbody")
    actuators = ET.SubElement(mj, "actuator")
    equality = ET.SubElement(mj, "equality")
    joint_order: list[tuple[str, str, float, float, float]] = []

    def add_link(parent_el, link_name, pos="0 0 0", euler="0 0 0", joint=None):
        link = links[link_name]
        body = ET.SubElement(parent_el, "body", name=link_name, pos=pos)
        if euler != "0 0 0":
            body.set("euler", euler)

        if joint is not None:
            jtype = joint.get("type")
            lim = joint.find("limit")
            j = ET.SubElement(body, "joint", name=RENAME.get(joint.get("name"), joint.get("name")),
                              type="hinge" if jtype == "revolute" else "slide",
                              axis=joint.find("axis").get("xyz"))
            if lim is not None:
                j.set("range", f'{lim.get("lower")} {lim.get("upper")}')
                joint_order.append((joint.get("name"), jtype, float(lim.get("lower")),
                                    float(lim.get("upper")), float(lim.get("effort"))))

        inr = link.find("inertial")
        if inr is not None:
            o = inr.find("origin")
            assert o is None or o.get("rpy", "0 0 0").split() == ["0", "0", "0"], link_name
            i = inr.find("inertia")
            ET.SubElement(body, "inertial",
                          pos=o.get("xyz") if o is not None else "0 0 0",
                          mass=inr.find("mass").get("value"),
                          fullinertia=" ".join(i.get(k) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")))

        for tag, cls in (("visual", "visual"), ("collision", "collision")):
            if cls == "collision" and link_name in FINGER_COLLISION:
                for p, half, name in FINGER_COLLISION[link_name]:
                    attrs = {"class": "collision"}
                    if name:
                        attrs["name"] = name
                    ET.SubElement(body, "geom", attrs, type="box", pos=fmt(p), size=fmt(half))
                continue
            for el in link.findall(tag):
                mesh = el.find("geometry/mesh")
                if mesh is None:
                    continue
                fname = os.path.basename(mesh.get("filename"))
                mname = os.path.splitext(fname)[0]
                if fname not in meshes:
                    meshes.add(fname)
                    ET.SubElement(asset, "mesh", name=mname, file=fname)
                g = ET.SubElement(body, "geom", {"class": cls}, mesh=mname)
                o = el.find("origin")
                if o is not None and o.get("xyz", "0 0 0") != "0 0 0":
                    g.set("pos", o.get("xyz"))
                if o is not None and o.get("rpy", "0 0 0") != "0 0 0":
                    g.set("euler", o.get("rpy"))
                color = el.find("material/color")
                if cls == "visual" and color is not None:
                    g.set("rgba", color.get("rgba"))

        if link_name == "gripper_link":
            # Punkt narzedzia miedzy plytkami szczek, tam gdzie biegna rownolegle
            # (plytki x = 0.03..0.06, czubki zagiete do srodka przy x = 0.078). Regula 5.
            ET.SubElement(body, "site", name="tcp", pos="0.045 0 0", size="0.005",
                          rgba="1 0 0 0.5", group="4")

        for cj in children.get(link_name, []):
            o = cj.find("origin")
            add_link(body, cj.find("child").get("link"),
                     pos=o.get("xyz", "0 0 0") if o is not None else "0 0 0",
                     euler=o.get("rpy", "0 0 0") if o is not None else "0 0 0",
                     joint=None if cj.get("type") == "fixed" else cj)

    add_link(world, root_link)

    # Serwo pozycyjne na kazdy staw ramienia i jedno na chwytak; aktuator nazwany jak staw (regula 2).
    for name, _jtype, lo, hi, effort in joint_order:
        if name == "gripper_finger_joint2":
            continue                        # jedzie przez rownosc ponizej
        kp = KP_GRIPPER if name == "gripper_finger_joint1" else KP[name]
        mj_name = RENAME.get(name, name)
        ET.SubElement(actuators, "position", name=mj_name, joint=mj_name, kp=str(kp), kv=str(kp / 20),
                      ctrlrange=fmt((lo, hi)), forcerange=fmt((-effort, effort)))
    ET.SubElement(equality, "joint", joint1="gripper_finger_joint2",
                  joint2=RENAME["gripper_finger_joint1"], polycoef="0 -1 0 0 0",
                  solref=MIRROR_SOLREF, solimp=MIRROR_SOLIMP)          # regula 6

    # Keyframe "home": poza uniesiona, zeby ramie nie lezalo na wlasnej podstawie.
    qpos = [HOME.get(n, 0.0) for n, *_ in joint_order]
    qpos[[n for n, *_ in joint_order].index("gripper_finger_joint2")] = -HOME["gripper_finger_joint1"]
    ctrl = [HOME.get(n, 0.0) for n, *_ in joint_order if n != "gripper_finger_joint2"]
    kf = ET.SubElement(mj, "keyframe")
    ET.SubElement(kf, "key", name="home", qpos=fmt(qpos), ctrl=fmt(ctrl))

    xml = minidom.parseString(ET.tostring(mj)).toprettyxml(indent="  ")
    xml = xml.replace('<?xml version="1.0" ?>\n', "")
    return HEADER.format(urdf=urdf.name) + xml


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="MJCF ramienia A1X z URDF producenta (dla blizniaka).")
    ap.add_argument("--urdf", type=Path, default=ASSET_DIR / "a1x.urdf", help="URDF producenta")
    ap.add_argument("--meshes", type=Path, default=ASSET_DIR / MESHDIR, help="katalog siatek STL z URDF")
    ap.add_argument("--out", type=Path, default=ASSET_DIR / "a1x.xml", help="plik MJCF do zapisania")
    a = ap.parse_args(argv)

    text = generate(a.urdf)
    out_meshes = a.out.parent / MESHDIR
    out_meshes.mkdir(parents=True, exist_ok=True)
    files = mesh_files(a.urdf)
    for fname in files:
        src, dst = a.meshes / fname, out_meshes / fname
        if src.resolve() != dst.resolve():
            shutil.copyfile(src, dst)
    a.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"zapisano {a.out} ({len(files)} siatek w {out_meshes})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
